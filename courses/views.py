class CohortViewSet(viewsets.ModelViewSet):
    queryset = Cohort.objects.select_related('course').all()
    serializer_class = CohortSerializer
    permission_classes = [IsStaffOrReadOnly]

    @action(detail=True, methods=['get'], permission_classes=[IsInstructorOrStaff])
    def members(self, request, pk=None):
        cohort = self.get_object()
        enrollments = cohort.enrollments.all()
        serializer = EnrollmentSerializer(enrollments, many=True)
        return Response(serializer.data)

    @action(detail=True, methods=['post'], permission_classes=[IsInstructorOrStaff])
    def bulk_enroll(self, request, pk=None):
        """Bulk enroll users by email list."""
        cohort = self.get_object()
        emails = request.data.get('emails', [])
        if not isinstance(emails, list):
            return Response({"error": "Emails field must be a list"}, status=status.HTTP_400_BAD_REQUEST)

        from users.models import User
        results = {"enrolled": [], "not_found": [], "already_enrolled": []}

        for email in emails:
            try:
                user = User.objects.get(email=email)
                enrollment, created = Enrollment.objects.get_or_create(
                    user=user, 
                    course=cohort.course,
                    defaults={'cohort': cohort}
                )
                if created:
                    results["enrolled"].append(email)
                else:
                    if enrollment.cohort != cohort:
                        enrollment.cohort = cohort
                        enrollment.save()
                        results["enrolled"].append(email)
                    else:
                        results["already_enrolled"].append(email)
            except User.DoesNotExist:
                results["not_found"].append(email)

        return Response(results)

    @action(detail=True, methods=['get'], permission_classes=[permissions.IsAuthenticated])
    def leaderboard(self, request, pk=None):
        cohort = self.get_object()
        # Check if user is enrolled in this cohort or is staff
        if not request.user.is_staff and not cohort.enrollments.filter(user=request.user).exists():
            return Response({"error": "You must be enrolled in this cohort to see the leaderboard."}, status=status.HTTP_403_FORBIDDEN)

        # Aggregate points: 10 points per completed lesson, 50 points per successful submission
        # This is a simplified gamification logic
        members = cohort.enrollments.select_related('user').all()
        leaderboard_data = []

        for enrollment in members:
            user = enrollment.user
            completed_lessons = Progress.objects.filter(user=user, lesson__module__course=cohort.course, is_completed=True).count()
            successful_submissions = Submission.objects.filter(user=user, problem__course=cohort.course, status='success').count()
            
            total_points = (completed_lessons * 10) + (successful_submissions * 50)
            
            leaderboard_data.append({
                "username": user.username,
                "completed_lessons": completed_lessons,
                "successful_submissions": successful_submissions,
                "total_points": total_points,
                "role": getattr(user, 'role', 'student')
            })

        # Sort by points descending
        leaderboard_data.sort(key=lambda x: x['total_points'], reverse=True)
        return Response(leaderboard_data)
